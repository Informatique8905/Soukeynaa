import type { NextConfig } from "next";

const isDev = process.env.NODE_ENV !== "production";

// En-têtes de sécurité (CDC 14) — CSP pragmatique pour Next.js : les
// scripts inline sont requis sans infrastructure de nonce ; 'unsafe-eval'
// uniquement en dev (HMR). frame-ancestors/XFO bloquent le clickjacking.
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: https:",
  "font-src 'self' data:",
  `connect-src 'self' https://api.cloudinary.com${isDev ? " ws:" : ""}`,
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  ...(isDev ? [] : ["upgrade-insecure-requests"]),
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=()",
  },
  ...(isDev
    ? []
    : [
        {
          key: "Strict-Transport-Security",
          value: "max-age=63072000; includeSubDomains; preload",
        },
      ]),
];

const nextConfig: NextConfig = {
  /* config options here */
  experimental: {
    // Cache client du routeur : re-navigations et retours instantanés.
    // revalidatePath côté serveur invalide les entrées sensibles (panier…).
    staleTimes: { dynamic: 30, static: 300 },
  },
  // Aperçu navigateur / téléphone sur le dev server (HMR, chunks dev)
  allowedDevOrigins: ["127.0.0.1", "192.168.16.1"],
  images: {
    remotePatterns: [
      {
        protocol: "https",
        hostname: "res.cloudinary.com",
      },
    ],
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
  turbopack: {
    root: import.meta.dirname,
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
